st.header("3. Логика роста MAU Hub (stock-and-flow + динамика MAU платформы)")

st.markdown("""
MAU Hub растёт по **stock-and-flow модели**: два входных потока (сайт + приложение)
конвертируют посетителей в пользователей из убывающих пулов. Убывающий пул —
это «резерв» потенциальных пользователей, которые ещё не конвертировались.

| Фаза | Период | MAU Hub (base) | Главные драйверы |
|---|---|---|---|
| **Phase 1** | М1–3 | ~1.0–1.5M | UX-редизайн: таб «Промо», triggered push; fresh_app ~340k/мес (1.0% × 34M) |
| **Phase 2** | М4–9 | ~2–3.5M | Накопление seg_low/mid/act; web→app миграция ~5% full-funnel; рост каталога |
| **Phase 3** | М10–24 | ~4–7M | Переходы LOW→MID→ACT; Data Flywheel; CLO-интеграции; Strategic-партнёры |

### 3.1 Динамика MAU платформы: почему MAU не константа

Базовая версия модели задавала MAU_web и MAU_app как **константы** — пул фиксирован с месяца 0.
Это занижает долгосрочный потенциал: T-Bank продолжает привлекать новых клиентов, а сайт
получает органический трафик. В реальности **пул пополняется** каждый месяц.

**Уравнение роста MAU платформы:**
```
MAU_web[m] = MAU_web_0 × (1 + r_web)^(m−1)
MAU_app[m] = MAU_app_0 × (1 + r_app)^(m−1)

r_web = (1 + web_annual_growth/100)^(1/12) − 1   [месячная ставка]
r_app = (1 + app_annual_growth/100)^(1/12) − 1
```

**Механизм пополнения пула:**
```
increment_web[m] = MAU_web[m] − MAU_web[m−1]   # прирост MAU сайта за месяц
increment_app[m] = MAU_app[m] − MAU_app[m−1]   # прирост MAU приложения

pool_web += increment_web × (1 − overlap/100)   # web-only новые пользователи
pool_app += increment_app                        # новые app-пользователи T-Bank
```
После пополнения пул деплетируется по стандартной схеме (u_web/u_app конвертация).

### 3.2 Обоснование базовых темпов роста

| Канал | Годовой рост (base) | Месячный рост | Источник и логика |
|---|---|---|---|
| **promokod.tbank.ru** | **35%** | ~2.5% | Hub-запуск → SEO-редизайн + платный трафик. Honey/PayPal web рос 40–60%/год в Y1–Y2 (оценочно). Купонатор/Промокод.ру при зрелости ~20%. 35% — умеренный сценарий для нового продукта со значительным брендовым буфером T-Bank. |
| **T-Bank App** | **18%** | ~1.4% | T-Bank MAU: 27M (9М2024) → 34M (FY2025) = **+26%** за год (T-Technologies IR FY2025). На горизонте 2 лет рост замедляется: Revolut при 30M+ MAU = 15–20%/год, Grab = 12–18%/год. 18% — консервативный base с учётом насыщения. |

### 3.3 Чувствительность модели к росту MAU

При росте MAU платформы пул не иссякает так быстро — Hub получает стабильный приток
новых потенциальных пользователей. Это особенно важно во Phase 3, когда органический пул
начинает истощаться: без роста MAU приложения приток fresh_app к месяцу 18 заметно падает.

При `app_annual_growth = 18%` к концу месяца 24:
- pool_app пополнился дополнительно ≈ 9,7M пользователей
- Это компенсирует истощение базового пула и поддерживает рост MAU Hub

### 3.4 Ключевое отличие от S-кривой

Старая модель задавала MAU Hub как фиксированный % от MAU T-Bank — «чёрный ящик».
Новая модель **явно отслеживает** каждую когорту:

- `pool_web` и `pool_app` — убывающие + **пополняемые** запасы потенциальных пользователей
- `mau_web_cur[m]` и `mau_app_cur[m]` — текущие MAU платформы на каждом месяце
- `new_app`, `new_web` — входящий поток NEW каждый месяц
- `seg_low / seg_mid / seg_act` — накопленные поведенческие сегменты
- `avg_rpu` — динамически рассчитывается из состава сегментов

**График 4** показывает:
- Закрашенные области = сегменты авторизованных Hub-пользователей (монетизируются)
- **Чёрная линия** = `mau_hub + new_web` = полный охват Hub (app + web), включая web-only

### 3.5 Почему выручка растёт быстрее MAU

Revenue = MAU_hub × Coverage × CTR × RR × avg_rpu. Все множители растут:

- **MAU_hub** — накопление seg_act к Phase 3 + стабильный приток из растущего пула
- **Redemption Rate** — CLO friction падает в Phase 3
- **avg_rpu** — доля ACT (3 покупки/мес) растёт → blended avg_rpu ↑
- **Revenue_per_redemption** — Strategic-партнёры с высоким AOV в Phase 2–3
""")

