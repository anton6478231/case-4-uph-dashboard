# 2. Центральная формула выручки
# ──────────────────────────────────────────────────────────────────────────────

st.header("2. Формула выручки")

st.markdown("""
**Базовая единица монетизации** — один **verified redemption**:
пользователь открыл оффер → кликнул → применил → T-Bank атрибутировал транзакцию.

### Шаг 1: Воронка (сколько redemptions за месяц)

```
N_redemptions = MAU_hub
              × Offer_Coverage     [% MAU, получивших ≥1 релевантный оффер]
              × CTR_offer          [% кликнувших на оффер]
              × Redemption_Rate    [% кликнувших, применивших оффер]
```

### Шаг 2: Выручка (два типа кампаний)

```
Revenue_CPA      = N_redemptions × share_CPA × CPA_avg
Revenue_RevShare = N_redemptions × (1 − share_CPA) × AOV_avg × RevShare_avg

Revenue_gross    = (Revenue_CPA + Revenue_RevShare) × Incremental_adj
```

**Поправка `Incremental_adj = 0.87`** учитывает, что ~13% выручки — это
перераспределение из существующих кешбек-контрактов Т-Банка (внутренняя каннибализация),
а не новый доход. Без поправки модель завышает прирост.

### Шаг 3: EBITDA

```
Variable_Costs = N_redemptions × VC_per_redemption   [₽/redemption, снижается с масштабом]
Fixed_Costs    = задаётся по фазе                     [ступенчатый рост]

EBITDA = Revenue_gross − Variable_Costs − Fixed_Costs
```
""")

