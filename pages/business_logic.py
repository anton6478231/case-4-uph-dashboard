# ──────────────────────────────────────────────────────────────────────────────
# 3. Рост MAU Hub
# ──────────────────────────────────────────────────────────────────────────────

st.header("3. Логика роста MAU Hub")

st.markdown("""
MAU Hub растёт по **S-кривой**, разбитой на 3 фазы. Каждая фаза имеет свои
драйверы роста и ceiling проникновения.

| Фаза | Период | Penetration | MAU Hub (base) | Главные драйверы |
|---|---|---|---|---|
| **Phase 1** | М1–3 | ~4.4% MAU T-Bank | ~1.5 млн | UX-редизайн: таб «Промо» в меню, виджет на главном экране, triggered push |
| **Phase 2** | М4–9 | ~9.4% MAU T-Bank | ~3.2 млн | Реферальная петля (K≈0.16–0.25), web→app конверсия (~5% неавт. посетителей), рост каталога партнёров |
| **Phase 3** | М10–24 | ~19% MAU T-Bank | ~6.5 млн | Self-serve кабинет, CLO-интеграции (Wildberries, Яндекс Маркет), cross-sell из брокера / страховок |

**Потолок:** MAU Hub не может превысить ~60–70% MAU T-Bank (~20–24 млн)
— доля аудитории, реально интересующейся промо-офферами (опрос v3: 60–70% позитивны).

### Почему выручка растёт быстрее MAU

Выручка = MAU_hub × CR × Revenue_per_redemption. Все три множителя растут одновременно:

- **MAU_hub** — S-кривая
- **Redemption Rate** — с ростом доли CLO friction падает: Phase 1 ~12%, Phase 3 ~25–32%
- **Revenue_per_redemption** — Strategic-партнёры с высоким AOV появляются в Phase 2–3

→ Совокупный рост нелинейный («хоккейная клюшка»). Важно ограничивать TAM-кепом.
""")

