with st.expander("Развернуть глоссарий", expanded=False):
    st.markdown("""
| Термин | Определение |
|---|---|
| **MAU Hub** | Monthly Active Users Unified Promo Hub — пользователи, открывшие раздел промо за месяц |
| **Offer Coverage** | % MAU Hub, которым алгоритм смог показать ≥1 релевантный оффер |
| **CTR (Click-Through Rate)** | % пользователей, кликнувших на оффер после его показа |
| **Redemption Rate** | % кликнувших, которые фактически применили оффер (совершили покупку) |
| **Verified Redemption** | Подтверждённое использование оффера: транзакция атрибутирована T-Bank-ом |
| **CPA (Cost Per Acquisition)** | Фиксированная ставка за один verified redemption. Партнёр платит независимо от суммы покупки |
| **RevShare** | % от суммы покупки (AOV), который партнёр платит за redemption |
| **AOV (Average Order Value)** | Средний чек покупки в рамках оффера |
| **CLO (Card-Linked Offer)** | Оффер, привязанный к карте: скидка применяется автоматически при оплате картой — без ввода кода |
| **Incremental_adj** | Поправка на каннибализацию: доля выручки, которая действительно инкрементальна (новая), а не перетянута из других продуктов T-Bank |
| **NBP (Next Best Promo)** | ML-алгоритм предиктивного подбора офферов под транзакционный профиль пользователя |
| **K-фактор** | Вирусный коэффициент реферальной петли: K = (приглашений на 1 пользователя) × (конверсия приглашения) |
| **Fixed Costs** | Затраты, не зависящие от числа redemptions: команда, инфраструктура, офис |
| **Variable Costs** | Затраты на 1 redemption: push, inference, attribution, antifraud, support |
| **EBITDA** | Earnings Before Interest, Taxes, Depreciation & Amortization = Revenue − Fixed − Variable |
| **Breakeven** | Месяц, когда накопленный Cash Flow впервые достигает нуля |
| **Data Flywheel** | Механизм самоусиления: больше redemptions → больше транзакционных данных → точнее NBP → выше CTR → больше redemptions |
| **pool_web / pool_app** | Убывающие пулы потенциальных пользователей (stock-and-flow): запас ещё не конвертировавшихся посетителей |
| **graduating** | Когорта пользователей, «выпускающихся» из NEW в сегменты LOW/MID/ACT в данном месяце |
| **avg_rpu** | Динамический avg redemptions per user: взвешенное среднее по составу сегментов |
""")


