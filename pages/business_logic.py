# 3. Рост MAU Hub
# ──────────────────────────────────────────────────────────────────────────────

st.header("3. Логика роста MAU Hub (stock-and-flow)")

st.markdown("""
MAU Hub растёт по **stock-and-flow модели**: два входных потока (сайт + приложение)
конвертируют посетителей в пользователей из убывающих пулов. Убывающий пул —
это «резерв» потенциальных пользователей, которые ещё не конвертировались.

| Фаза | Период | MAU Hub (base) | Главные драйверы |
|---|---|---|---|
| **Phase 1** | М1–3 | ~500k | UX-редизайн: таб «Промо», triggered push; fresh_app ~170k/мес |
| **Phase 2** | М4–9 | ~1.5–2M | Накопление seg_low/mid/act; web→app миграция; рост каталога |
| **Phase 3** | М10–24 | ~3–5M+ | Переходы LOW→MID→ACT; Data Flywheel; CLO-интеграции |

### Ключевое отличие от S-кривой

Старая модель задавала MAU Hub как фиксированный % от MAU T-Bank — «чёрный ящик».
Новая модель **явно отслеживает** каждую когорту:

- `pool_web` и `pool_app` — убывающие запасы потенциальных пользователей
- `new_app`, `new_web` — входящий поток NEW каждый месяц
- `seg_low / seg_mid / seg_act` — накопленные поведенческие сегменты
- `avg_rpu` — динамически рассчитывается из состава сегментов

### Почему выручка растёт быстрее MAU

Revenue = MAU_hub × Coverage × CTR × RR × avg_rpu. Все множители растут:

- **MAU_hub** — накопление seg_act к Phase 3
- **Redemption Rate** — CLO friction падает в Phase 3
- **avg_rpu** — доля ACT (3 покупки/мес) растёт → blended avg_rpu ↑
- **Revenue_per_redemption** — Strategic-партнёры с высоким AOV в Phase 2–3
""")

