def pie(labels, values, title, height=320):
    fig = go.Figure(go.Pie(
        labels=labels, values=values,
        marker=dict(colors=COLORS_PIE[:len(labels)]),
        textinfo="percent+label",
        textfont_size=12,
        hole=0.35,
    ))
    fig.update_layout(
        title_text=title, title_font_size=13,
        margin=dict(t=50, b=20, l=10, r=10),
        height=height,
        legend=dict(font_size=11),
        showlegend=True,
    )
    return fig


def hbar(labels, values, title, height=None):
    if height is None:
        height = max(260, 40 * len(labels) + 80)
    fig = go.Figure(go.Bar(
        x=values, y=labels,
        orientation="h",
        marker_color=COLORS_MULTI[:len(labels)],
        text=[f"{v}%" for v in values],
        textposition="outside",
    ))
    fig.update_layout(
        title_text=title, title_font_size=13,
        xaxis=dict(range=[0, max(values) * 1.25], ticksuffix="%"),
        margin=dict(t=50, b=20, l=10, r=50),
        height=height,
        showlegend=False,
    )
    return fig


